students = []

def add_student():
    name = input("Enter student name: ")
    marks = []
    for i in range(1, 6):
        marks.append(int(input("Enter mark" + str(i) + ": ")))
    total = sum(marks)
    average = total / 5

    if average >= 80:
        grade = "A Grade"
    elif average >= 60:
        grade = "B Grade"
    elif average >= 50:
        grade = "C Grade"
    else:
        grade = "Fail"

    students.append([name, total, average, grade])
    print("Student added.")

def view_report():
    if len(students) == 0:
        print("No students yet.")
        return
    print("\n---Student Report---")
    for s in students:
        print("Name:", s[0], "| Total:", s[1], "| Average:", round(s[2], 1), "|", s[3])

def find_topper():
    if len(students) == 0:
        print("No students yet.")
        return
    topper = students[0]
    for s in students:
        if s[1] > topper[1]:
            topper = s
    print("Topper:", topper[0], "with total", topper[1])

def save_report():
    with open("report.txt", "w") as f:
        f.write("---Student Report---\n")
        for s in students:
            f.write("Name: " + s[0] + " | Total: " + str(s[1]) + " | Average: " + str(round(s[2], 1)) + " | " + s[3] + "\n")
    print("Report saved to report.txt")

